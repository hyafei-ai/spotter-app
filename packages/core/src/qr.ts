/**
 * Minimal QR Code encoder (byte mode, ISO/IEC 18004), used for invite QR codes in the coach app.
 * Kept dependency-free so it runs the same on device, on the web and in tests.
 * Structure follows the standard reference algorithm: function patterns, Reed–Solomon ECC,
 * block interleaving, and masking chosen by penalty score.
 */

export type Ecl = 'L' | 'M' | 'Q' | 'H';
const ECL_INDEX: Record<Ecl, number> = { L: 0, M: 1, Q: 2, H: 3 };
const ECL_FORMAT_BITS: Record<Ecl, number> = { L: 1, M: 0, Q: 3, H: 2 };

